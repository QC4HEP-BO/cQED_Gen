"""
Tests for circuit2graph.expansion.

The important invariant is round-trip invertibility at primitive-block level:

    primitive raw graph -> graphlize -> expand_topology -> graphlize

must reproduce the same macro graph, and, for graphlize-produced macro graphs,
the expanded primitive graph must be isomorphic to the original primitive graph.
"""

