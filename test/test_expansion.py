def test_expand_graphlize_user_examples_is_inverse(name: str, builder: Callable[[], CQEDTopology]) -> None:
    _assert_round_trip(builder())


def test_expand_single_macro_nodes_respects_direction_and_attrs() -> None:
    cases = [
        (SubgType.TC, {"L": 1.0, "C": 2.0, "Cc": 3.0, "dir": 1.0}, [SubgType.TRANSMON, SubgType.C_COUPLER]),
        (SubgType.TC, {"L": 1.0, "C": 2.0, "Cc": 3.0, "dir": -1.0}, [SubgType.C_COUPLER, SubgType.TRANSMON]),
        (SubgType.RC, {"length": 4.0, "Cc": 3.0, "dir": 1.0}, [SubgType.RESONATOR, SubgType.C_COUPLER]),
        (SubgType.RC, {"length": 4.0, "Cc": 3.0, "dir": -1.0}, [SubgType.C_COUPLER, SubgType.RESONATOR]),
        (SubgType.RI, {"length": 4.0, "D": 9.0, "l": 0.1, "dir": 1.0}, [SubgType.RESONATOR, SubgType.I_COUPLER]),
        (SubgType.RI, {"length": 4.0, "D": 9.0, "l": 0.1, "dir": -1.0}, [SubgType.I_COUPLER, SubgType.RESONATOR]),
        (SubgType.RCT, {"length": 4.0, "Cc": 3.0, "L": 1.0, "C": 2.0, "dir": 1.0}, [SubgType.RESONATOR, SubgType.C_COUPLER, SubgType.TRANSMON]),
        (SubgType.RCT, {"length": 4.0, "Cc": 3.0, "L": 1.0, "C": 2.0, "dir": -1.0}, [SubgType.TRANSMON, SubgType.C_COUPLER, SubgType.RESONATOR]),
        (SubgType.TCT, {"L": 1.0, "C": 2.0, "Cc": 3.0, "L2": 4.0, "C2": 5.0, "dir": 1.0}, [SubgType.TRANSMON, SubgType.C_COUPLER, SubgType.TRANSMON]),
    ]
    for subg_type, attrs, expected_types in cases:
        node = type("N", (), {"subg_type": subg_type, "attrs": attrs, "node_id": 17, "label": None})()
        specs = expand_node_to_primitives(node)
        assert [s.subg_type for s in specs] == expected_types


def build_feedline_two_branch_hub_plus_cycle() -> CQEDTopology:
    """Stress case similar to the screenshot: feedline hub, TCT, RC and a cycle."""
    t = CQEDTopology("feedline_two_branch_hub_plus_cycle")
    f = t.add_node(SubgType.FEEDLINE, {}, label="F")
    c_entry = t.add_node(SubgType.C_COUPLER, _cc_attrs(2e-15), label="C_entry")
    c31 = t.add_node(SubgType.C_COUPLER, _cc_attrs(3e-15), label="C31")
    r3 = t.add_node(SubgType.RESONATOR, _r_attrs(0.00334), label="R3")
    c23 = t.add_node(SubgType.C_COUPLER, _cc_attrs(4e-15), label="C23")
    t2 = t.add_node(SubgType.TRANSMON, _t_attrs(11e-9), label="T2")
    c12 = t.add_node(SubgType.C_COUPLER, _cc_attrs(5e-15), label="C12")
    t1 = t.add_node(SubgType.TRANSMON, _t_attrs(12e-9), label="T1")
    c_leaf = t.add_node(SubgType.C_COUPLER, _cc_attrs(6e-15), label="C_leaf")

    t.add_edge(f, c_entry)
    t.add_edge(c_entry, c31)
    t.add_edge(c_entry, r3)
    t.add_edge(c_entry, t1)
    t.add_edge(c31, c23)
    t.add_edge(c23, t2)
    t.add_edge(t2, c12)
    t.add_edge(c12, t1)
    t.add_edge(r3, c23)
    # disconnected-ish leaf connected to entry to make hub degree high and add an unmerged coupler leaf
    t.add_edge(c_entry, c_leaf)
    return t


def build_inductive_resonator_line_and_hub() -> CQEDTopology:
    t = CQEDTopology("inductive_resonator_line_and_hub")
    f = t.add_node(SubgType.FEEDLINE, {}, label="F")
    c = t.add_node(SubgType.C_COUPLER, _cc_attrs(1e-15), label="C_feed")
    r1 = t.add_node(SubgType.RESONATOR, _r_attrs(0.0030), label="R1")
    ind1 = t.add_node(SubgType.I_COUPLER, _i_attrs(9.0, 1e-4), label="I1")
    r2 = t.add_node(SubgType.RESONATOR, _r_attrs(0.0032), label="R2")
    ind2 = t.add_node(SubgType.I_COUPLER, _i_attrs(10.0, 2e-4), label="I2")
    r3 = t.add_node(SubgType.RESONATOR, _r_attrs(0.0034), label="R3")
    q = t.add_node(SubgType.TRANSMON, _t_attrs(13e-9), label="T")
    cq = t.add_node(SubgType.C_COUPLER, _cc_attrs(7e-15), label="Cq")
    t.add_edge(f, c); t.add_edge(c, r1)
    t.add_edge(r1, ind1); t.add_edge(ind1, r2)
    t.add_edge(r2, ind2); t.add_edge(ind2, r3)
    t.add_edge(r2, cq); t.add_edge(cq, q)
    return t


def build_four_transmon_capacitive_ring_with_tail() -> CQEDTopology:
    t = CQEDTopology("four_transmon_capacitive_ring_with_tail")
    q1 = t.add_node(SubgType.TRANSMON, _t_attrs(10e-9), label="T1")
    c12 = t.add_node(SubgType.C_COUPLER, _cc_attrs(1e-15), label="C12")
    q2 = t.add_node(SubgType.TRANSMON, _t_attrs(11e-9), label="T2")
    c23 = t.add_node(SubgType.C_COUPLER, _cc_attrs(2e-15), label="C23")
    q3 = t.add_node(SubgType.TRANSMON, _t_attrs(12e-9), label="T3")
    c34 = t.add_node(SubgType.C_COUPLER, _cc_attrs(3e-15), label="C34")
    q4 = t.add_node(SubgType.TRANSMON, _t_attrs(13e-9), label="T4")
    c41 = t.add_node(SubgType.C_COUPLER, _cc_attrs(4e-15), label="C41")
    r = t.add_node(SubgType.RESONATOR, _r_attrs(0.004), label="R_tail")
    cr = t.add_node(SubgType.C_COUPLER, _cc_attrs(5e-15), label="CR_tail")
    for a, b in [(q1, c12), (c12, q2), (q2, c23), (c23, q3), (q3, c34), (c34, q4), (q4, c41), (c41, q1), (q3, cr), (cr, r)]:
        t.add_edge(a, b)
    return t


