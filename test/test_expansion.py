def _i_attrs(D: float = 9.0, l: float = 1.3e-4) -> dict[str, float]:
    return {"D": D, "l": l}


def _safe_filename(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", name).strip("_") or "topology"


def _plot_round_trip(raw: CQEDTopology, compressed: CQEDTopology, expanded: CQEDTopology) -> Path:
    """Save the three-step visual debug plot: primitive -> macro -> re-expanded.

    The plots are intentionally generated by the test itself, so running pytest
    gives both correctness checks and visual artifacts useful for debugging the
    expansion/compression inversion.  Override the output folder with:

        CQED_EXPANSION_PLOT_DIR=/path/to/plots pytest test/test_expansion.py
    """
    PLOT_DIR.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 3, figsize=(21, 6))

    for ax, topology, title in [
        (axes[0], raw, "1. INPUT primitive / inner graph"),
        (axes[1], compressed, "2. COMPRESSED macro graph"),
        (axes[2], expanded, "3. RE-EXPANDED primitive / inner graph"),
    ]:
        topology.draw(ax=ax, with_labels=True)
        ax.set_title(f"{title}\n{topology.name}", fontsize=10)

    fig.suptitle(
        f"Expansion round trip: {raw.name}\n"
        f"nodes {len(raw._nodes)} -> {len(compressed._nodes)} -> {len(expanded._nodes)}, "
        f"edges {len(raw._edges)} -> {len(compressed._edges)} -> {len(expanded._edges)}",
        fontsize=12,
    )
    fig.tight_layout()

    out_path = PLOT_DIR / f"{_safe_filename(raw.name)}__primitive_macro_reexpanded.png"
    fig.savefig(out_path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    return out_path


def _assert_round_trip(raw: CQEDTopology, *, make_plot: bool = True) -> None:
    compressed = graphlize(raw)
    expanded = expand_topology(compressed, validate=True)
    recompressed = graphlize(expanded)

    assert topologies_equivalent(expanded, raw, check_labels=False), raw.name
    assert topologies_equivalent(recompressed, compressed, check_labels=False), raw.name

    if make_plot:
        plot_path = _plot_round_trip(raw, compressed, expanded)
        assert plot_path.exists(), plot_path


