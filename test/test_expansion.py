def test_expand_predicted_unlabelled_macro_graph_is_recompressible() -> None:
    """Model outputs may not have compression labels; expansion must still work."""
    g = CQEDTopology("predicted_unlabelled_macro")
    c = g.add_node(SubgType.C_COUPLER, {"Cc": 1e-15}, label=None)
    tct = g.add_node(SubgType.TCT, {"L": 10e-9, "C": 70e-15, "Cc": 2e-15, "L2": 11e-9, "C2": 71e-15, "dir": 1.0}, label=None)
    rct = g.add_node(SubgType.RCT, {"length": 0.0035, "Cc": 3e-15, "L": 12e-9, "C": 72e-15, "dir": -1.0}, label=None)
    rc = g.add_node(SubgType.RC, {"length": 0.0038, "Cc": 4e-15, "dir": 1.0}, label=None)
    g.add_edge(c, tct)
    g.add_edge(c, rct)
    g.add_edge(tct, rc)

    expanded = expand_topology(g, validate=True)
    assert all(n.subg_type in {SubgType.FEEDLINE, SubgType.TRANSMON, SubgType.RESONATOR, SubgType.C_COUPLER, SubgType.I_COUPLER} for n in expanded._nodes)
    assert topologies_equivalent(graphlize(expanded), g, check_labels=False)

    # Visual debug artifact for the model-output setting: the macro graph is
    # already the input, so panel 1 and panel 2 are both macro-level, while
    # panel 3 shows the deterministic primitive expansion.
    plot_path = _plot_round_trip(graphlize(expanded), g, expanded)
    assert plot_path.exists(), plot_path
