def nx_typed_graph(g: Any) -> nx.Graph:
    G = nx.Graph()
    for i, st in enumerate(g.node_types):
        G.add_node(int(i), node_type=int(st))
    for u, v in g.edges:
        if int(u) != int(v):
            G.add_edge(int(u), int(v))
    return G


def typed_isomorphism_mapping(g_true: Any, g_pred: Any) -> dict[int, int] | None:
    if len(g_true.node_types) != len(g_pred.node_types):
        return None
    if len(g_true.edges) != len(g_pred.edges):
        # Isomorphic simple graphs must have equal edge counts; cheap early exit.
        return None
    Gt = nx_typed_graph(g_true)
    Gp = nx_typed_graph(g_pred)
    matcher = nx.algorithms.isomorphism.GraphMatcher(
        Gt,
        Gp,
        node_match=lambda a, b: int(a["node_type"]) == int(b["node_type"]),
    )
    try:
        return next(matcher.isomorphisms_iter())
    except StopIteration:
        return None


def reorder_pred_to_true(g_pred: Any, true_to_pred: dict[int, int], n_true: int) -> SimpleNamespace:
    pred_to_true = {int(p): int(t) for t, p in true_to_pred.items()}
    node_types = [int(g_pred.node_types[int(true_to_pred[i])]) for i in range(n_true)]
    attrs_src = getattr(g_pred, "attrs", []) or []
    attrs = []
    for i in range(n_true):
        p = int(true_to_pred[i])
        attrs.append(dict(attrs_src[p]) if p < len(attrs_src) else {})
    edges = []
    seen = set()
    for u, v in getattr(g_pred, "edges", []) or []:
        if int(u) not in pred_to_true or int(v) not in pred_to_true:
            continue
        a, b = pred_to_true[int(u)], pred_to_true[int(v)]
        if a == b:
            continue
        key = tuple(sorted((a, b)))
        if key not in seen:
            seen.add(key)
            edges.append(key)
    return SimpleNamespace(node_types=node_types, edges=edges, attrs=attrs)


def _direction_value(attrs: dict[str, Any] | None) -> float:
    if not attrs:
        return float("nan")
    for key in ("dir", "direction"):
        if key in attrs:
            try:
                return float(attrs[key])
            except Exception:
                return float("nan")
    return float("nan")


def topology_record(family: str, branch: str, g_true: Any, g_pred: Any) -> tuple[dict[str, Any], list[tuple[str, str]], Any]:
    """Return topology metrics, node confusion pairs, and pred graph aligned if isomorphic."""
    repo_tm = ice.topo_match(g_true.node_types, g_true.edges, g_pred.node_types, g_pred.edges)
    mapping = typed_isomorphism_mapping(g_true, g_pred)
    exact_iso = mapping is not None
    g_pred_aligned = reorder_pred_to_true(g_pred, mapping, len(g_true.node_types)) if mapping else None

    # Node-type comparison: use the physical/isomorphic mapping where available;
    # otherwise fall back to the decoder's canonical sequence positions.
    node_pairs: list[tuple[str, str]] = []
    n_correct = 0
    n_true = len(g_true.node_types)
    n_pred = len(g_pred.node_types)
    if mapping is not None:
        for ti, t in enumerate(g_true.node_types):
            pi = int(mapping[ti])
            p = g_pred.node_types[pi]
            ts = SubgType(int(t)).name
            ps = SubgType(int(p)).name
            node_pairs.append((ts, ps))
            n_correct += int(int(t) == int(p))
        # no extras possible for an isomorphism
    else:
        n_max = max(n_true, n_pred)
        for i in range(n_max):
            ts = SubgType(int(g_true.node_types[i])).name if i < n_true else NONE_NODE
            ps = SubgType(int(g_pred.node_types[i])).name if i < n_pred else NONE_NODE
            node_pairs.append((ts, ps))
            if i < n_true and i < n_pred and int(g_true.node_types[i]) == int(g_pred.node_types[i]):
                n_correct += 1

    # Edge metrics are order-independent when an isomorphism exists. Otherwise
    # retain the repository canonical-index decomposition.
    if exact_iso:
        edge_tp = len(g_true.edges)
        edge_fp = 0
        edge_fn = 0
    else:
        edge_tp = int(repo_tm["edge_tp"])
        edge_fp = int(repo_tm["edge_fp"])
        edge_fn = int(repo_tm["edge_fn"])

    # Direction is not part of the topology-equality criterion.
    dir_true = 0
    dir_valid = 0
    dir_correct = 0
    true_attrs = getattr(g_true, "attrs", []) or []
    pred_attrs = getattr(g_pred, "attrs", []) or []
    for ti, attrs_t in enumerate(true_attrs):
        dt = _direction_value(attrs_t)
        if not np.isfinite(dt):
            continue
        dir_true += 1
        if mapping is not None:
            pi = int(mapping[ti])
        else:
            pi = ti
        if pi >= len(pred_attrs) or pi >= len(g_pred.node_types):
            continue
        if int(g_pred.node_types[pi]) != int(g_true.node_types[ti]):
            continue
        dp = _direction_value(pred_attrs[pi])
        if not np.isfinite(dp):
            continue
        dir_valid += 1
        dir_correct += int((dp >= 0) == (dt >= 0))

    rec = {
        "branch": branch,
        "family": family,
        "family_display": pretty_family(family),
        "exact_isomorphic": int(exact_iso),
        "exact_ordered": int(bool(repo_tm["exact"])),
        "n_true": n_true,
        "n_pred": n_pred,
        "abs_node_count_error": abs(n_pred - n_true),
        "n_correct_nodes": n_correct,
        "edge_tp": edge_tp,
        "edge_fp": edge_fp,
        "edge_fn": edge_fn,
        "dir_n_true": dir_true,
        "dir_n_valid": dir_valid,
        "dir_n_correct": dir_correct,
    }
    return rec, node_pairs, g_pred_aligned


def aggregate_topology(records: list[dict[str, Any]]) -> dict[str, float]:
    if not records:
        return {
            "n_samples": 0,
            "topology_accuracy": float("nan"),
            "ordered_topology_accuracy": float("nan"),
            "node_type_accuracy": float("nan"),
            "edge_precision": float("nan"),
            "edge_recall": float("nan"),
            "edge_f1": float("nan"),
            "node_count_mae": float("nan"),
            "direction_accuracy": float("nan"),
            "direction_coverage": float("nan"),
        }
    n = len(records)
    n_true = sum(int(r["n_true"]) for r in records)
    n_correct = sum(int(r["n_correct_nodes"]) for r in records)
    tp = sum(int(r["edge_tp"]) for r in records)
    fp = sum(int(r["edge_fp"]) for r in records)
    fn = sum(int(r["edge_fn"]) for r in records)
    p = tp / (tp + fp) if tp + fp else float("nan")
    r = tp / (tp + fn) if tp + fn else float("nan")
    f1 = 2 * p * r / (p + r) if np.isfinite(p) and np.isfinite(r) and p + r else float("nan")
    d_true = sum(int(x["dir_n_true"]) for x in records)
    d_valid = sum(int(x["dir_n_valid"]) for x in records)
    d_corr = sum(int(x["dir_n_correct"]) for x in records)
    return {
        "n_samples": n,
        "topology_accuracy": float(np.mean([r_["exact_isomorphic"] for r_ in records])),
        "ordered_topology_accuracy": float(np.mean([r_["exact_ordered"] for r_ in records])),
        "node_type_accuracy": n_correct / max(n_true, 1),
        "edge_precision": p,
        "edge_recall": r,
        "edge_f1": f1,
        "node_count_mae": float(np.mean([r_["abs_node_count_error"] for r_ in records])),
        "direction_accuracy": d_corr / d_valid if d_valid else float("nan"),
        "direction_coverage": d_valid / d_true if d_true else float("nan"),
        "n_exact": int(sum(int(r_["exact_isomorphic"]) for r_ in records)),
        "n_exact_ordered": int(sum(int(r_["exact_ordered"]) for r_ in records)),
    }


