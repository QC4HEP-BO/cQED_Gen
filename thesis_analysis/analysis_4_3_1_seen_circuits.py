def _scaler_arrays(ds_scaler: Any) -> list[np.ndarray]:
    out = []
    for obj in (getattr(ds_scaler, "param_scaler", None), getattr(ds_scaler, "obs_scaler", None)):
        if obj is None:
            continue
        for attr in ("mean_", "std_"):
            arr = getattr(obj, attr, None)
            if arr is not None:
                out.append(np.asarray(arr, dtype=np.float64))
    return out


def checkpoint_scalers_for_families(checkpoint_scalers: dict[str, Any], fresh_scalers: dict[str, Any]) -> dict[str, Any]:
    """Return checkpoint scalers mapped to every training family.

    New global-scaler checkpoints normally contain both the family aliases and
    ``__global__``. Older/simplified checkpoints may contain only ``__global__``.
    """
    out = dict(checkpoint_scalers or {})
    global_sc = out.get("__global__")
    if global_sc is not None:
        for family in train_datasets():
            out.setdefault(family, global_sc)
    # A missing checkpoint scaler is allowed only as a fallback; this is printed
    # explicitly so the final analysis is never silently using a different scaler.
    for family, sc in fresh_scalers.items():
        if family == "__global__":
            continue
        if family not in out:
            print(f"WARNING: checkpoint scaler missing for {family}; using freshly reconstructed scaler.")
            out[family] = sc
    return out


def verify_scaler_consistency(checkpoint_scalers: dict[str, Any], fresh_scalers: dict[str, Any], atol: float = 1e-9) -> None:
    families = [f for f in train_datasets() if f in fresh_scalers and f in checkpoint_scalers]
    worst = 0.0
    worst_family = None
    for family in families:
        a = _scaler_arrays(checkpoint_scalers[family])
        b = _scaler_arrays(fresh_scalers[family])
        if len(a) != len(b):
            raise RuntimeError(f"Scaler structure mismatch for {family}.")
        for x, y in zip(a, b):
            if x.shape != y.shape:
                raise RuntimeError(f"Scaler shape mismatch for {family}: {x.shape} vs {y.shape}.")
            d = float(np.max(np.abs(x - y))) if x.size else 0.0
            if d > worst:
                worst = d
                worst_family = family
    print(f"Scaler consistency: max |checkpoint-fresh| = {worst:.3e}" + (f" ({worst_family})" if worst_family else ""))
    if worst > atol:
        raise RuntimeError(
            "The dataset scaler reconstructed by the current repository/data does not match the scaler "
            f"stored in the checkpoint (max difference {worst:.3e} > {atol:.1e}). "
            "Because encoder features are precomputed by the loader, continuing would mix incompatible "
            "normalizations. Use the exact repository/data used for the final training run."
        )


