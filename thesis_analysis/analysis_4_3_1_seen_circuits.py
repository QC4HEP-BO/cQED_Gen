def plot_confusion(confusion_pairs: list[dict[str, Any]], out_path: Path) -> None:
    labels = NODE_LABELS + [NONE_NODE]
    idx = {name: i for i, name in enumerate(labels)}
    fig, axes = plt.subplots(1, 2, figsize=(13.2, 5.7))
    for ax, branch, title in zip(axes, ["circuit", "spec"], [r"$G\rightarrow G$", r"$H\rightarrow G$"]):
        mat = np.zeros((len(labels), len(labels)), dtype=float)
        for r in confusion_pairs:
            if r["branch"] != branch:
                continue
            mat[idx[r["true_node_type"]], idx[r["pred_node_type"]]] += 1
        row_sum = mat.sum(axis=1, keepdims=True)
        norm = np.divide(mat, row_sum, out=np.zeros_like(mat), where=row_sum > 0)
        im = ax.imshow(norm, vmin=0.0, vmax=1.0, cmap="Blues", aspect="auto")
        ax.set_title(title)
        ax.set_xlabel("Predicted macro-node type")
        ax.set_ylabel("True macro-node type")
        ax.set_xticks(range(len(labels)))
        ax.set_yticks(range(len(labels)))
        ax.set_xticklabels(labels, rotation=60, ha="right", fontsize=7)
        ax.set_yticklabels(labels, fontsize=7)
        # annotate only non-negligible cells to avoid clutter
        for i in range(len(labels)):
            for j in range(len(labels)):
                if norm[i, j] >= 0.02:
                    ax.text(j, i, f"{norm[i,j]:.2f}", ha="center", va="center", fontsize=6,
                            color="white" if norm[i, j] > 0.55 else "black")
    fig.colorbar(im, ax=axes.ravel().tolist(), fraction=0.025, pad=0.02, label="Row-normalized fraction")
    fig.subplots_adjust(left=0.08, right=0.91, bottom=0.24, top=0.90, wspace=0.30)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)


