def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Sec. 4.3.1 seen-circuit inference analysis for cQED-Gen")
    p.add_argument("--ckpt", default="best_vae_global.pt")
    p.add_argument("--split", default="test", choices=["train", "val", "test"])
    p.add_argument("--out-dir", default="analysis_results/4_3_1_seen_circuits")
    p.add_argument("--batch-size", type=int, default=128)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--runs", type=int, default=10, help="Independent metric subsampling runs.")
    p.add_argument("--samples-per-run", type=int, default=500, help="M circuits per repeated topology study.")
    p.add_argument("--max-per-family", type=int, default=0, help="Diagnostic cap for neural inference; 0 = use full split.")
    p.add_argument("--stochastic", action="store_true", help="Use stochastic decoder sampling. Default is deterministic.")
    p.add_argument("--no-permutation-eval", action="store_true")
    p.add_argument("--no-qultra", action="store_true")
    p.add_argument("--qultra-branches", default="spec", choices=["spec", "circuit", "both"],
                   help="Which branch(es) receive QuLTRA physical validation.")
    p.add_argument("--qultra-max-per-family", type=int, default=0,
                   help="Max QuLTRA attempts per family/selected branch; 0 = all samples (default).")
    p.add_argument("--f-min", type=float, default=1.0)
    p.add_argument("--f-max", type=float, default=9.0)
    p.add_argument("--scaler-atol", type=float, default=1e-9)
    return p.parse_args()


def main() -> None:
    args = parse_args()
    set_seed(args.seed)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Repository : {REPO_ROOT}")
    print(f"Device     : {device}")
    print(f"Checkpoint : {args.ckpt}")
    print(f"Split      : {args.split}")

    ckpt_path = Path(args.ckpt)
    if not ckpt_path.is_absolute():
        ckpt_path = REPO_ROOT / ckpt_path
    if not ckpt_path.exists():
        raise FileNotFoundError(ckpt_path)

    # Repository checkpoint loader reconstructs model + exact saved scaler dict.
    model, checkpoint_scalers, cfg = ice.load_checkpoint(str(ckpt_path), device)

    print("\nReconstructing deterministic dataset split...")
    train_data, val_data, test_data, fresh_scalers = load_all_datasets_vae(
        train_frac=cfg.get("train_frac", 0.70),
        val_frac=cfg.get("val_frac", 0.15),
        seed=cfg.get("seed", args.seed),
        max_nodes=cfg.get("max_nodes", 12),
    )
    scalers = checkpoint_scalers_for_families(checkpoint_scalers, fresh_scalers)
    verify_scaler_consistency(scalers, fresh_scalers, atol=args.scaler_atol)

    split_data = {"train": train_data, "val": val_data, "test": test_data}[args.split]
    # Seen-circuit thesis analysis should normally remain on the TEST split.
    if args.split != "test":
        print("WARNING: Sec. 4.3.1 is intended for the test split; you selected", args.split)
    data = optionally_limit_per_family(split_data, args.max_per_family, args.seed)
    print(f"Samples selected: {len(data)}")
    for family, items in sorted(group_by_family(data).items()):
        print(f"  {pretty_family(family):28s}: {len(items)}")

    qultra_branch_set = {
        "spec": {"spec"},
        "circuit": {"circuit"},
        "both": {"circuit", "spec"},
    }[args.qultra_branches]

    all_topo: list[dict[str, Any]] = []
    all_confusion: list[dict[str, Any]] = []
    all_params: list[dict[str, Any]] = []
    all_ham: list[dict[str, Any]] = []
    all_qultra_status: list[dict[str, Any]] = []

    for branch in ("circuit", "spec"):
        print("\n" + "=" * 82)
        print("CIRCUIT BRANCH G -> z_c -> G" if branch == "circuit" else "HAMILTONIAN BRANCH H -> z_s -> G")
        print("=" * 82)
        result = evaluate_branch(
            model=model,
            data=data,
            scalers=scalers,
            device=device,
            branch=branch,
            batch_size=args.batch_size,
            stochastic=args.stochastic,
            use_permutation_eval=not args.no_permutation_eval,
            qultra_enabled=(not args.no_qultra and branch in qultra_branch_set),
            qultra_max_per_family=args.qultra_max_per_family,
            f_min=args.f_min,
            f_max=args.f_max,
            seed=args.seed,
        )
        all_topo.extend(result["topology_records"])
        all_confusion.extend(result["confusion_pairs"])
        all_params.extend(result["parameter_rows"])
        all_ham.extend(result["hamiltonian_rows"])
        all_qultra_status.extend(result["qultra_status"])

    # ------------------------------------------------------------------
    # Topology tables and repeated M=500, N=10 studies
    # ------------------------------------------------------------------
    full_topo = build_full_topology_rows(all_topo)
    overall_runs, family_runs = repeated_topology_studies(
        all_topo,
        runs=args.runs,
        samples_per_run=args.samples_per_run,
        seed=args.seed + 101,
    )
    run_summary = summarize_run_rows(overall_runs, ["branch"])
    run_summary += summarize_run_rows(family_runs, ["branch", "family", "family_display"])

    node_errors = node_class_error_rows(all_confusion)
    confusion_counts = confusion_count_rows(all_confusion)

    # ------------------------------------------------------------------
    # Parameter tables
    # ------------------------------------------------------------------
    param_family = aggregate_error_rows(all_params, ["branch", "family", "family_display", "parameter"])
    param_aggregate = aggregate_error_rows(all_params, ["branch", "parameter_base"])

    # ------------------------------------------------------------------
    # QuLTRA/Hamiltonian tables
    # ------------------------------------------------------------------
    ham_family = aggregate_error_rows(all_ham, ["branch", "family", "family_display", "category", "observable"])
    ham_aggregate = aggregate_error_rows(all_ham, ["branch", "category"])

    # ------------------------------------------------------------------
    # Save all raw/aggregated outputs
    # ------------------------------------------------------------------
    write_csv(full_topo, out_dir / "seen_topology_full.csv")
    write_csv(overall_runs, out_dir / "seen_topology_runs_overall.csv")
    write_csv(family_runs, out_dir / "seen_topology_runs_per_family.csv")
    write_csv(run_summary, out_dir / "seen_topology_run_summary.csv")
    write_csv(node_errors, out_dir / "seen_node_type_error_by_class.csv")
    write_csv(confusion_counts, out_dir / "seen_node_confusion_counts.csv")

    write_csv(all_params, out_dir / "seen_parameter_errors_raw.csv")
    write_csv(param_family, out_dir / "seen_parameter_errors_by_family.csv")
    write_csv(param_aggregate, out_dir / "seen_parameter_errors_aggregate.csv")

    write_csv(all_ham, out_dir / "seen_hamiltonian_errors_raw.csv")
    write_csv(ham_family, out_dir / "seen_hamiltonian_errors_by_family.csv")
    write_csv(ham_aggregate, out_dir / "seen_hamiltonian_errors_aggregate.csv")
    write_csv(all_qultra_status, out_dir / "seen_qultra_status.csv")

    discussion = final_discussion_rows(full_topo, node_errors, param_aggregate, ham_aggregate)
    write_csv(discussion, out_dir / "seen_final_discussion_summary.csv")

    # ------------------------------------------------------------------
    # PDF diagnostics
    # ------------------------------------------------------------------
    plot_topology_metrics(full_topo, out_dir / "figure_seen_topology_metrics.pdf")
    plot_confusion(all_confusion, out_dir / "figure_seen_node_confusion.pdf")
    plot_parameter_errors(param_aggregate, out_dir / "figure_seen_parameter_errors.pdf")
    if ham_aggregate:
        plot_hamiltonian_errors(ham_aggregate, out_dir / "figure_seen_hamiltonian_errors.pdf")

    # ------------------------------------------------------------------
    # Headline summary for direct thesis insertion
    # ------------------------------------------------------------------
    headline: dict[str, Any] = {
        "checkpoint": str(ckpt_path),
        "split": args.split,
        "n_samples_total": len(data),
        "runs": args.runs,
        "samples_per_run": args.samples_per_run,
        "deterministic_inference": not args.stochastic,
        "topology_full": full_topo,
        "topology_repeated_run_summary": run_summary,
        "node_type_errors": node_errors,
        "parameter_error_aggregate": param_aggregate,
        "hamiltonian_error_aggregate": ham_aggregate,
        "qultra_status": all_qultra_status,
        "final_discussion": discussion,
    }
    (out_dir / "seen_inference_summary.json").write_text(
        json.dumps(jsonable(headline), indent=2), encoding="utf-8"
    )

    # Console headline.
    print("\n" + "=" * 82)
    print("HEADLINE RESULTS")
    print("=" * 82)
    for branch in ("circuit", "spec"):
        full = next(r for r in full_topo if r["scope"] == "overall" and r["branch"] == branch)
        rs = next(r for r in run_summary if r.get("branch") == branch and "family" not in r)
        name = "G -> G" if branch == "circuit" else "H -> G"
        print(
            f"{name:8s}: full A_topo={100*full['topology_accuracy']:.3f}% | "
            f"{args.runs}x{args.samples_per_run}: "
            f"{100*rs['topology_accuracy_mean']:.3f} +/- {100*rs['topology_accuracy_std']:.3f}% | "
            f"node={100*full['node_type_accuracy']:.3f}% | edge F1={full['edge_f1']:.5f} | "
            f"S_N={full['node_count_mae']:.5f}"
        )
    if ham_aggregate:
        print("\nHamiltonian relative-error medians / P90:")
        for r in ham_aggregate:
            print(
                f"  {r['branch']:7s} {r['category']:12s}: "
                f"median={r['median_relative_error_percent']:.4g}%  "
                f"P90={r['p90_relative_error_percent']:.4g}%  N={r['n']}"
            )
    print(f"\nOutputs -> {out_dir.resolve()}")


if __name__ == "__main__":
    main()
