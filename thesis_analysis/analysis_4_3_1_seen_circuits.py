def repeated_topology_studies(
    records: list[dict[str, Any]],
    runs: int,
    samples_per_run: int,
    seed: int,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Overall and family-wise independent random M-sample studies."""
    rng = np.random.default_rng(seed)
    overall_rows: list[dict[str, Any]] = []
    family_rows: list[dict[str, Any]] = []

    by_branch: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in records:
        by_branch[str(r["branch"])].append(r)

    for branch, items in sorted(by_branch.items()):
        for run in range(runs):
            m = min(samples_per_run, len(items)) if samples_per_run > 0 else len(items)
            idx = rng.choice(len(items), size=m, replace=False)
            subset = [items[int(i)] for i in idx]
            metric = aggregate_topology(subset)
            overall_rows.append({"branch": branch, "run": run + 1, **metric})

        families = sorted({str(r["family"]) for r in items})
        for family in families:
            fam_items = [r for r in items if r["family"] == family]
            for run in range(runs):
                m = min(samples_per_run, len(fam_items)) if samples_per_run > 0 else len(fam_items)
                idx = rng.choice(len(fam_items), size=m, replace=False)
                subset = [fam_items[int(i)] for i in idx]
                metric = aggregate_topology(subset)
                family_rows.append({
                    "branch": branch,
                    "family": family,
                    "family_display": pretty_family(family),
                    "run": run + 1,
                    **metric,
                })
    return overall_rows, family_rows


def summarize_run_rows(rows: list[dict[str, Any]], group_keys: list[str]) -> list[dict[str, Any]]:
    metrics = [
        "topology_accuracy",
        "ordered_topology_accuracy",
        "node_type_accuracy",
        "edge_precision",
        "edge_recall",
        "edge_f1",
        "node_count_mae",
        "direction_accuracy",
    ]
    grouped: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        grouped[tuple(row.get(k) for k in group_keys)].append(row)
    out = []
    for key, items in sorted(grouped.items(), key=lambda kv: tuple(str(x) for x in kv[0])):
        rec = {k: v for k, v in zip(group_keys, key)}
        for metric in metrics:
            vals = [finite_or_nan(x.get(metric)) for x in items]
            rec[f"{metric}_mean"] = safe_mean(vals)
            rec[f"{metric}_std"] = safe_std(vals)
        rec["n_runs"] = len(items)
        rec["samples_per_run"] = items[0].get("n_samples", 0) if items else 0
        out.append(rec)
    return out


