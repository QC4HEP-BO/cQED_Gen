def group_by_family(samples: list[Any]) -> dict[str, list[Any]]:
    out: dict[str, list[Any]] = defaultdict(list)
    for s in samples:
        out[str(s.dataset_name)].append(s)
    return dict(out)


def optionally_limit_per_family(samples: list[Any], n: int, seed: int) -> list[Any]:
    if n <= 0:
        return list(samples)
    rng = np.random.default_rng(seed)
    out: list[Any] = []
    for family, items in sorted(group_by_family(samples).items()):
        if len(items) <= n:
            chosen = list(items)
        else:
            idx = rng.choice(len(items), size=n, replace=False)
            chosen = [items[int(i)] for i in idx]
        out.extend(chosen)
    rng.shuffle(out)
    return out


