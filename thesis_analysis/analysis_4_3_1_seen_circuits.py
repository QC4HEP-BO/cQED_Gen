@torch.no_grad()
def evaluate_branch(
    model: Any,
    data: list[Any],
    scalers: dict[str, Any],
    device: torch.device,
    branch: str,
    batch_size: int,
    stochastic: bool,
    use_permutation_eval: bool,
    qultra_enabled: bool,
    qultra_max_per_family: int,
    f_min: float,
    f_max: float,
    seed: int,
) -> dict[str, Any]:
    assert branch in {"circuit", "spec"}
    model.eval()
    grouped = group_by_family(data)
    ds_map = ice._get_dataset_id_mapping(data)

    topo_records: list[dict[str, Any]] = []
    confusion_pairs: list[dict[str, Any]] = []
    parameter_rows: list[dict[str, Any]] = []
    hamiltonian_rows: list[dict[str, Any]] = []
    qultra_status: list[dict[str, Any]] = []

    qu = None
    if qultra_enabled:
        if ihq is None:
            print(f"WARNING: inference_hamiltonian_qultra.py could not be imported: {_IHQ_IMPORT_ERROR}")
            qultra_enabled = False
        elif not getattr(ihq, "_HAS_QULTRA_WORKFLOW", False):
            print("WARNING: repository QuLTRA workflow is unavailable; skipping Hamiltonian validation.")
            qultra_enabled = False
        else:
            try:
                qu = ihq.import_qultra()
            except Exception as exc:
                print(f"WARNING: QuLTRA import failed ({type(exc).__name__}: {exc}); skipping Hamiltonian validation.")
                qultra_enabled = False

    rng = np.random.default_rng(seed + (0 if branch == "circuit" else 10000))

    for family, samples in sorted(grouped.items()):
        print(f"\n[{branch}] {pretty_family(family)}: N={len(samples)}")
        scaler_bundle = scalers[family]
        param_scaler = scaler_bundle.param_scaler
        obs_scaler = scaler_bundle.obs_scaler

        if qultra_enabled:
            if qultra_max_per_family <= 0 or qultra_max_per_family >= len(samples):
                qultra_positions = set(range(len(samples)))
            else:
                qultra_positions = set(int(i) for i in rng.choice(len(samples), size=qultra_max_per_family, replace=False))
        else:
            qultra_positions = set()

        n_qultra_attempted = 0
        n_qultra_success = 0
        fail_reasons = Counter()

        for start in range(0, len(samples), batch_size):
            batch = samples[start:start + batch_size]
            if branch == "circuit":
                z, _, _ = model.encode(batch, scalers)
            else:
                obs_vals = torch.stack([s.obs_vals for s in batch], dim=0).to(device)
                obs_mask = torch.stack([s.obs_mask for s in batch], dim=0).to(device)
                z, _, _ = model.spec_encoder.encode(obs_vals, obs_mask)

            graphs_pred, _ = ice._decode_graphs(model, z, batch, stochastic, ds_map)

            for local_i, (sample, g_pred) in enumerate(zip(batch, graphs_pred)):
                family_i = start + local_i
                # sample.y is scaled; the graph object is sufficient for true types/edges/dir.
                g_true = ice.data_to_graph_ns(sample, param_scaler)
                trec, pairs, g_pred_aligned = topology_record(family, branch, g_true, g_pred)
                trec["sample_index_in_family"] = family_i
                topo_records.append(trec)
                for t, p in pairs:
                    confusion_pairs.append({
                        "branch": branch,
                        "family": family,
                        "family_display": pretty_family(family),
                        "true_node_type": t,
                        "pred_node_type": p,
                    })

                # ------------------------------------------------------
                # Circuit parameters: only physically matching topology.
                # ------------------------------------------------------
                if g_pred_aligned is not None and getattr(g_pred_aligned, "attrs", None):
                    true_row_scaled = np.asarray(sample.y.detach().cpu().numpy(), dtype=float)
                    pred_row_scaled = np.asarray(ice._scaled_attr_row_from_pred_graph(g_pred_aligned), dtype=float)
                    attr_names = ice._unique_attr_names_from_graph(g_true)
                    if len(pred_row_scaled) == len(true_row_scaled) == len(attr_names):
                        if use_permutation_eval:
                            perms = ice._get_attr_perm_indices(sample, len(true_row_scaled))
                            pred_row_scaled, _, _ = ice._best_pred_row_aligned_to_true_order(
                                true_row_scaled, pred_row_scaled, perms
                            )
                            pred_row_scaled = np.asarray(pred_row_scaled, dtype=float)

                        inverse_names = [name.rsplit("_n", 1)[0] if "_n" in name else name for name in attr_names]
                        true_phys = param_scaler.inverse_transform(true_row_scaled, inverse_names)
                        pred_phys = param_scaler.inverse_transform(pred_row_scaled, inverse_names)
                        for name, tv, pv in zip(attr_names, true_phys, pred_phys):
                            if not (np.isfinite(tv) and np.isfinite(pv)):
                                continue
                            parameter_rows.append({
                                "branch": branch,
                                "family": family,
                                "family_display": pretty_family(family),
                                "parameter": name,
                                "parameter_base": base_attr_name(name),
                                "true": float(tv),
                                "pred": float(pv),
                                "relative_error_percent": float(rel_err_percent(tv, pv)),
                            })

                # ------------------------------------------------------
                # QuLTRA validation: reuse the repository evaluator.
                # Reordered predicted graph makes the evaluator robust to a
                # physically irrelevant decoder-node permutation.
                # ------------------------------------------------------
                if family_i in qultra_positions:
                    n_qultra_attempted += 1
                    if g_pred_aligned is None:
                        fail_reasons["topology_not_isomorphic"] += 1
                    else:
                        try:
                            qrec, _tm, reason = ihq._maybe_physics_eval_sample(
                                sample,
                                g_pred_aligned,
                                param_scaler,
                                obs_scaler,
                                qu,
                                f_min,
                                f_max,
                                use_permutation_eval,
                            )
                        except Exception as exc:
                            qrec = None
                            reason = f"exception:{type(exc).__name__}"
                        if qrec is None:
                            fail_reasons[reason or "unknown"] += 1
                        else:
                            n_qultra_success += 1
                            hamiltonian_rows.extend(hamiltonian_rows_from_record(branch, family, qrec))

            if len(samples) >= 1000 and (start == 0 or (start // batch_size + 1) % 10 == 0):
                print(f"  {min(start + len(batch), len(samples))}/{len(samples)}")

        qultra_status.append({
            "branch": branch,
            "family": family,
            "family_display": pretty_family(family),
            "qultra_enabled": int(qultra_enabled),
            "qultra_attempted": n_qultra_attempted,
            "qultra_successful": n_qultra_success,
            "qultra_success_fraction": n_qultra_success / n_qultra_attempted if n_qultra_attempted else float("nan"),
            "failure_reasons": json.dumps(dict(fail_reasons), sort_keys=True),
        })

    return {
        "topology_records": topo_records,
        "confusion_pairs": confusion_pairs,
        "parameter_rows": parameter_rows,
        "hamiltonian_rows": hamiltonian_rows,
        "qultra_status": qultra_status,
    }


