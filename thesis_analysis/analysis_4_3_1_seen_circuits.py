def aggregate_error_rows(
    rows: list[dict[str, Any]],
    group_keys: list[str],
    error_key: str = "relative_error_percent",
) -> list[dict[str, Any]]:
    grouped: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        grouped[tuple(row.get(k) for k in group_keys)].append(row)
    out: list[dict[str, Any]] = []
    for key, items in sorted(grouped.items(), key=lambda kv: tuple(str(x) for x in kv[0])):
        vals = np.asarray([finite_or_nan(x.get(error_key)) for x in items], dtype=float)
        vals = vals[np.isfinite(vals)]
        rec = {k: v for k, v in zip(group_keys, key)}
        rec.update({
            "n": int(vals.size),
            "median_relative_error_percent": float(np.median(vals)) if vals.size else float("nan"),
            "p90_relative_error_percent": float(np.percentile(vals, 90)) if vals.size else float("nan"),
            "mean_relative_error_percent": float(np.mean(vals)) if vals.size else float("nan"),
        })
        out.append(rec)
    return out


def hamiltonian_rows_from_record(branch: str, family: str, rec: dict[str, Any]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    true = rec.get("true", {})
    pred = rec.get("pred_aligned", {})

    tf = np.asarray(true.get("frequencies", []), dtype=float)
    pf = np.asarray(pred.get("frequencies", []), dtype=float)
    for i in range(min(len(tf), len(pf))):
        if np.isfinite(tf[i]) and np.isfinite(pf[i]):
            out.append({
                "branch": branch,
                "family": family,
                "family_display": pretty_family(family),
                "category": "frequency",
                "observable": f"f_{i+1}",
                "true": float(tf[i]),
                "pred": float(pf[i]),
                "absolute_error": float(abs(pf[i] - tf[i])),
                "relative_error_percent": float(rel_err_percent(tf[i], pf[i])),
                "near_zero_true": int(abs(tf[i]) < 1e-12),
            })

    tk = np.asarray(true.get("kappa", []), dtype=float)
    pk = np.asarray(pred.get("kappa", []), dtype=float)
    for i in range(min(len(tk), len(pk))):
        if np.isfinite(tk[i]) and np.isfinite(pk[i]):
            out.append({
                "branch": branch,
                "family": family,
                "family_display": pretty_family(family),
                "category": "kappa",
                "observable": f"kappa_{i+1}",
                "true": float(tk[i]),
                "pred": float(pk[i]),
                "absolute_error": float(abs(pk[i] - tk[i])),
                "relative_error_percent": float(rel_err_percent(tk[i], pk[i])),
                "near_zero_true": int(abs(tk[i]) < 1e-12),
            })

    tc = np.asarray(true.get("chi", np.zeros((0, 0))), dtype=float)
    pc = np.asarray(pred.get("chi", np.zeros((0, 0))), dtype=float)
    n = min(tc.shape[0] if tc.ndim == 2 else 0, pc.shape[0] if pc.ndim == 2 else 0)
    for i in range(n):
        for j in range(i, n):
            if not (np.isfinite(tc[i, j]) and np.isfinite(pc[i, j])):
                continue
            category = "self_kerr" if i == j else "cross_kerr"
            out.append({
                "branch": branch,
                "family": family,
                "family_display": pretty_family(family),
                "category": category,
                "observable": f"chi_{i+1}{j+1}",
                "true": float(tc[i, j]),
                "pred": float(pc[i, j]),
                "absolute_error": float(abs(pc[i, j] - tc[i, j])),
                "relative_error_percent": float(rel_err_percent(tc[i, j], pc[i, j])),
                "near_zero_true": int(abs(tc[i, j]) < 1e-12),
            })
    return out


